"""Грузинские имена вместо английских в предложениях-примерах.

Почти все примеры взяты из Tatoeba, а там действуют Том и Мэри. В тренажёре
грузинского им не место, поэтому все имена заменяются на два грузинских:
мужские — на Давид, женские — на Нино. Имён нарочно два: меньше форм, меньше ошибок в падежах. Пол
сохраняется, иначе разъехалось бы согласование глаголов в русском переводе.

Пары имён подобраны так, чтобы склонялись одинаково:
  ტომ- → დავით-   (обе основы на согласный: ტომმა/დავითმა, ტომს/დავითს)
  Том → Давид     (Тома/Давида, Тому/Давиду, Томом/Давидом)
  მერი → ნინო,  Мэри → Нино   (в русском оба не склоняются)
Поэтому Том и Мэри заменяются по основе в любом падеже, а редкие имена —
целыми предложениями: их мало, и падежи у них не совпадают.

Реальные люди (Толстой, Обама, Бьорк), клички животных и города не трогаем.

  python3 tools/localize_names.py      # правит data/examples.json на месте
Тот же шаг вызывает build_examples.py, так что пересборка имён не вернёт.
"""
