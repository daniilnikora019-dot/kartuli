def localize_ka(t):
    t = WHOLE.get(t, t)
    t = re.sub(rf'(?<![{GEO}])ტომითვის', 'დავითისთვის', t)   # нестандартная форма → правильная
    t = re.sub(rf'(?<![{GEO}])ტომ', 'დავით', t)
    t = re.sub(rf'(?<![{GEO}])მერი', 'ნინო', t)
    return t


def localize_ru(t):
    t = WHOLE_RU.get(t, t)
    t = re.sub(r'\bТом(а|у|ом|е)?\b', lambda m: 'Давид' + (m.group(1) or ''), t)
    t = re.sub(r'\bМэри\b', 'Нино', t)
    return t


def localize(ka, ru):
    return localize_ka(ka), localize_ru(ru)


def main():
    data = json.load(open(OUT, encoding='utf-8'))
    words = {w['id']: w['ka'].lower()
             for w in json.load(open(f'{BASE}/data/words.json', encoding='utf-8'))['words']}
    # ручной слой написан сразу правильно: там მერი — «мэр», а ტომი — «том»
    manual = f'{BASE}/data/examples-manual.json'
    keep = set(json.load(open(manual, encoding='utf-8'))) if os.path.exists(manual) else set()
    changed = dropped = 0
    for wid in list(data):
        if wid in keep: continue
        new = []
        for ka, ru in data[wid]:
            nka, nru = localize(ka, ru)
            # Пример попал к слову из-за самого имени: მერი — «мэр», ტომი — «том»,
            # მელა — «лиса» внутри «Мелани». После замены слова в нём нет — убираем.
            if words.get(wid, '') in ka.lower() and words.get(wid, '') not in nka.lower():
                dropped += 1
                continue
            changed += (nka, nru) != (ka, ru)
            new.append([nka, nru])
        if new: data[wid] = new
        else: del data[wid]
    json.dump(data, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    print(f'изменено предложений: {changed}, убрано ошибочных: {dropped}')


if __name__ == '__main__':
    main()
